# ── 饮水计划 ──
# 依据《中国居民膳食指南（2022）》：成年男性 1700ml、女性 1500ml 为最低推荐量
# （饮水量，不含食物中水分）；实际按体重 30–35 ml/kg 估算，天热/运动再加。
WATER_SLOTS = [
    ("晨起", 0.10, "起床后空腹先喝，补偿整夜的水分丢失"),
    ("上午", 0.22, "9–11 点分两次，每次 150–200ml"),
    ("午餐前", 0.12, "饭前 30 分钟，别边吃边大量喝水"),
    ("下午", 0.26, "14–17 点分两到三次，最容易忘的时段"),
    ("晚餐前", 0.12, "饭前 30 分钟"),
    ("晚间", 0.18, "睡前 1 小时内少喝，避免起夜"),
]


def water_plan(weight, activity="轻度活动"):
    """全天饮水量（ml）与分时段分配。

    基础按 30 ml/kg 估算，活动量高再加 300–500 ml；
    下限 1500 ml（女性指南值）、上限 3000 ml，避免过量。
    """
    extra = {"久坐": 0, "轻度活动": 200, "中度活动": 400, "高强度": 500}.get(activity, 200)
    total = int(round(weight * 30)) + extra
    total = max(1500, min(3000, total))
    plan = []
    acc = 0
    for name, ratio, note in WATER_SLOTS:
        ml = int(round(total * ratio / 50.0)) * 50     # 取整到 50ml，更好执行
        plan.append({"slot": name, "ml": ml, "note": note})
        acc += ml
    # 差额补到「下午」（最容易忘、也最需要补的时段）
    diff = total - acc
    if diff:
        for it in plan:
            if it["slot"] == "下午":
                it["ml"] += diff
                break
    return {"total": total, "plan": plan}
